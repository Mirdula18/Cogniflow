// Scans lib/mock/scenarios/*.json and lib/mock/datasets/*.profile.json and writes
// lib/mock/registry.generated.ts with static imports, so new scenario or dataset
// files are picked up without code changes. Runs before dev, build, test and typecheck.
import { readdirSync, writeFileSync } from "node:fs";

const mockDir = new URL("../lib/mock/", import.meta.url);

function list(dir, suffix) {
  try {
    return readdirSync(new URL(`${dir}/`, mockDir))
      .filter((f) => f.endsWith(suffix))
      .sort();
  } catch {
    return [];
  }
}

const scenarios = list("scenarios", ".json");
const datasets = list("datasets", ".profile.json");

const lines = [
  "// AUTO-GENERATED by scripts/gen-mock-registry.mjs. Do not edit.",
  ...scenarios.map((f, i) => `import scenario${i} from "./scenarios/${f}";`),
  ...datasets.map((f, i) => `import dataset${i} from "./datasets/${f}";`),
  "",
  `export const scenarioFiles: unknown[] = [${scenarios.map((_, i) => `scenario${i}`).join(", ")}];`,
  `export const datasetFiles: unknown[] = [${datasets.map((_, i) => `dataset${i}`).join(", ")}];`,
  "",
];

writeFileSync(new URL("registry.generated.ts", mockDir), lines.join("\n"));
console.log(`mock registry: ${scenarios.length} scenario(s), ${datasets.length} dataset profile(s)`);
